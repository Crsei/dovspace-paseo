#!/usr/bin/env node
// Generates the PM palette module from the PM repository's theme tokens. The app never
// reads PM source at runtime; this script is the single bridge between the two repos.
//
// PM's `:root` and `.dark` blocks carry the base palette; the browser preference layer
// (`data-pm-accent="indigo"`) carries the effective accent. Paseo keeps PM's base
// `--primary`/`--primary-foreground` as legacy aliases because PM's accent preference
// overrides buttons but not every Paseo consumer of the legacy pair.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const pmRoot = path.resolve(root, "..", "project-management-agent-v4");
const themePath = path.join(pmRoot, "apps", "web", "src", "styles", "theme.css");
const preferencePath = [
  path.join(pmRoot, "apps", "web", "src", "features", "workspace", "preferences.css"),
  path.join(pmRoot, "apps", "web", "src", "styles", "preferences.css"),
].find((candidate) => existsSync(candidate));
const generatedPath = path.join(root, "packages", "app", "src", "styles", "pm-tokens.gen.ts");
const check = process.argv.includes("--check");

// PM has no `surface4` or `accentBright`. `surface4` continues PM's pressed-surface step
// (the next fill used by Paseo), and `accentBright` is the brighter accent used for focus
// and hover accents. Both stay with the generator so the committed module has one source.
const PASEO_EXTENSIONS = {
  light: { surface4: "#dcdcd6", accentBright: "#6b78e0" },
  dark: { surface4: "#363632", accentBright: "#c4caff" },
};

function blockDeclarations(css, selector) {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const pattern = /([^{}]+)\{([^{}]*)\}/g;
  let match;
  while ((match = pattern.exec(withoutComments)) !== null) {
    const candidate = match[1].trim().replace(/\s+/g, " ");
    if (candidate !== selector) continue;
    const declarations = new Map();
    for (const declaration of match[2].split(";")) {
      const at = declaration.indexOf(":");
      if (at === -1) continue;
      const name = declaration.slice(0, at).trim();
      if (name.startsWith("--")) declarations.set(name, declaration.slice(at + 1).trim());
    }
    return declarations;
  }
  throw new Error(`Could not find the ${selector} block in the PM stylesheets`);
}

function resolver(...layers) {
  const raw = new Map();
  for (const layer of layers) {
    for (const [name, value] of layer) raw.set(name, value);
  }
  const cache = new Map();
  function resolve(name, seen = new Set()) {
    if (cache.has(name)) return cache.get(name);
    const value = raw.get(name);
    if (value === undefined) throw new Error(`PM stylesheet does not declare ${name}`);
    if (seen.has(name)) throw new Error(`Circular PM variable reference at ${name}`);
    seen.add(name);
    const resolved = value.replace(/var\((--[a-z0-9-]+)\)/gi, (_match, reference) =>
      resolve(reference, new Set(seen)),
    );
    cache.set(name, resolved);
    return resolved;
  }
  return {
    value(name) {
      return resolve(name).replace(/\s+/g, " ").trim().toLowerCase();
    },
  };
}

function hex(resolve, name) {
  const value = resolve.value(name);
  if (!/^#[0-9a-f]{6}$/.test(value)) {
    throw new Error(`Expected ${name} to be a 6-digit hex color, received ${value}`);
  }
  return value;
}

function statusColors(base) {
  return {
    statusSuccess: hex(base, "--success"),
    statusDanger: hex(base, "--destructive"),
    statusWarning: hex(base, "--warning"),
    statusMerged: hex(base, "--agent"),
  };
}

function renderObject(object, indent = "") {
  const entries = Object.entries(object).map(
    ([key, value]) => `${indent}  ${key}: ${JSON.stringify(value)},`,
  );
  return `{\n${entries.join("\n")}\n${indent}}`;
}

function render() {
  return `// Generated by scripts/pm/sync-theme-tokens.mjs from the PM theme stylesheets.
// Do not edit by hand. Run \`npm run pm:theme-tokens\` to regenerate.
//
// PM defines no surface4 or accentBright token; those two values live in the generator.

export const PM_LIGHT_COLORS = ${renderObject(lightColors)} as const;

export const PM_DARK_COLORS = ${renderObject(darkColors)} as const;

export const PM_STATUS_COLORS = {
  light: ${renderObject(statusColors(lightBase), "  ")},
  dark: ${renderObject(statusColors(darkBase), "  ")},
} as const;

// PM tints status fills with color-mix(... 8%, surface): 0.08 * 255 = 20.4 -> 0x14.
export const PM_STATUS_TINT_ALPHA = "14";
`;
}

if (!existsSync(pmRoot)) {
  console.log(`PM checkout not found at ${pmRoot}; skipping PM theme token sync.`);
  process.exit(0);
}

if (!existsSync(themePath)) {
  throw new Error(`PM theme stylesheet not found at ${themePath}`);
}
if (preferencePath === undefined) {
  throw new Error("PM browser preferences stylesheet not found");
}

const themeCss = readFileSync(themePath, "utf8");
const preferenceCss = readFileSync(preferencePath, "utf8");

const rootTheme = blockDeclarations(themeCss, ":root");
const darkTheme = blockDeclarations(themeCss, ".dark");
const indigo = blockDeclarations(preferenceCss, 'html[data-pm-accent="indigo"]');
const accentOverride = blockDeclarations(preferenceCss, "html[data-pm-accent]");
const darkAccentOverride = blockDeclarations(preferenceCss, "html.dark[data-pm-accent]");

// Base blocks keep the legacy `primary` pair; the accent preference overrides it, so read
// accent, ring, and their foreground from the effective (override-applied) layers.
const lightBase = resolver(rootTheme);
const lightEffective = resolver(rootTheme, indigo, accentOverride);
const darkBase = resolver(darkTheme);
const darkEffective = resolver(darkTheme, indigo, accentOverride, darkAccentOverride);

const lightColors = {
  surface0: hex(lightEffective, "--surface"),
  surface1: hex(lightEffective, "--surface-raised"),
  surface2: hex(lightEffective, "--surface-hover"),
  surface3: hex(lightEffective, "--surface-pressed"),
  surface4: PASEO_EXTENSIONS.light.surface4,
  surfaceSidebar: hex(lightEffective, "--background"),
  foreground: hex(lightEffective, "--foreground"),
  foregroundMuted: hex(lightEffective, "--text-secondary"),
  foregroundExtraMuted: hex(lightEffective, "--text-muted"),
  border: lightEffective.value("--border"),
  borderAccent: lightEffective.value("--border-hover"),
  accent: hex(lightEffective, "--accent"),
  accentBright: PASEO_EXTENSIONS.light.accentBright,
  accentForeground: hex(lightEffective, "--accent-foreground"),
  primary: hex(lightBase, "--primary"),
  primaryForeground: hex(lightBase, "--primary-foreground"),
  destructive: hex(lightEffective, "--destructive"),
  ring: hex(lightEffective, "--ring"),
};

const darkColors = {
  surface0: hex(darkEffective, "--surface"),
  surface1: hex(darkEffective, "--surface-raised"),
  surface2: hex(darkEffective, "--surface-hover"),
  surface3: hex(darkEffective, "--surface-pressed"),
  surface4: PASEO_EXTENSIONS.dark.surface4,
  surfaceSidebar: hex(darkEffective, "--background"),
  foreground: hex(darkEffective, "--foreground"),
  foregroundMuted: hex(darkEffective, "--text-secondary"),
  foregroundExtraMuted: hex(darkEffective, "--text-muted"),
  border: darkEffective.value("--border"),
  borderAccent: darkEffective.value("--border-hover"),
  accent: hex(darkEffective, "--accent"),
  accentBright: PASEO_EXTENSIONS.dark.accentBright,
  accentForeground: hex(darkEffective, "--accent-foreground"),
  primary: hex(darkBase, "--primary"),
  primaryForeground: hex(darkBase, "--primary-foreground"),
  destructive: hex(darkEffective, "--destructive"),
  ring: hex(darkEffective, "--ring"),
};

const next = render();
const current = existsSync(generatedPath) ? readFileSync(generatedPath, "utf8") : "";
const normalize = (content) => content.replace(/\r\n/g, "\n").trimEnd();

if (check) {
  if (normalize(current) !== normalize(next)) {
    console.error(
      `PM theme tokens are out of date at ${path.relative(root, generatedPath)}. Run npm run pm:theme-tokens.`,
    );
    process.exitCode = 1;
  } else {
    console.log("PM theme tokens are up to date.");
  }
} else if (normalize(current) === normalize(next)) {
  console.log(`PM theme tokens already current at ${path.relative(root, generatedPath)}.`);
} else {
  writeFileSync(generatedPath, next);
  console.log(`wrote ${path.relative(root, generatedPath)}`);
}
