#!/usr/bin/env node
// Vendors the dependency-free PM transport and page registry into the built-in
// plugin. Built-in plugins cannot import workspace packages at runtime, so these
// files are generated copies and checked for drift by `--check`.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const targets = [
  ["packages/pm-integration/src/http.ts", "plugins/dovspace-pm/server/vendor/pm-http.gen.ts"],
  ["packages/pm-integration/src/pages.ts", "plugins/dovspace-pm/server/vendor/pm-pages.gen.ts"],
];
const check = process.argv.includes("--check");

function banner(source, sourcePath) {
  const hash = createHash("sha256").update(source).digest("hex");
  return `// Generated by scripts/pm/sync-plugin-vendor.mjs from ${sourcePath}. Do not edit by hand.\n// Source sha256: ${hash}\n\n${source}`;
}

const baseline = JSON.parse(
  await readFile(path.join(root, "docs", "pm-integration-baseline.json"), "utf8"),
);
targets.push(["@pm-contract-metadata", "plugins/dovspace-pm/server/vendor/pm-contract.gen.ts"]);

let drift = false;
for (const [sourcePath, targetPath] of targets) {
  const source =
    sourcePath === "@pm-contract-metadata"
      ? `export const PM_CONTRACT_METADATA = ${JSON.stringify(
          {
            version: baseline.openapiVersion ?? baseline.pmVersion,
            pmVersion: baseline.pmVersion,
            pmCommit: baseline.pmCommit,
            openapiSha256: baseline.openapiSha256,
            operationCount: baseline.operationCount,
            pathCount: baseline.pathCount,
          },
          null,
          2,
        )} as const;\n`
      : await readFile(path.join(root, sourcePath), "utf8");
  const expected = banner(
    source,
    sourcePath === "@pm-contract-metadata" ? "docs/pm-integration-baseline.json" : sourcePath,
  );
  const absoluteTarget = path.join(root, targetPath);
  if (check) {
    const current = await readFile(absoluteTarget, "utf8").catch(() => "");
    if (current !== expected) {
      console.error(`out of date: ${targetPath}`);
      drift = true;
    }
    continue;
  }
  await mkdir(path.dirname(absoluteTarget), { recursive: true });
  await writeFile(absoluteTarget, expected);
  console.log(`wrote ${targetPath}`);
}

if (check && drift) {
  console.error("Run: node scripts/pm/sync-plugin-vendor.mjs");
  process.exitCode = 1;
}
